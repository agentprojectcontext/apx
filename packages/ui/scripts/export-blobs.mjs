// Regenerates src/blobs/catalog.ts from APX v1's blob export: every eyeless body
// PNG becomes a 128px webp data-URI (retina for avatars up to 64px) next to its
// eye rects, so the package carries its own blobs and needs no public/ folder.
// Usage: node scripts/export-blobs.mjs [path-to-v1-web]   (needs `cwebp` on PATH)

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const web = resolve(process.argv[2] ?? "../../../apx/src/interfaces/web");
const presets = readFileSync(join(web, "src/components/agents/blobPresets.ts"), "utf8");
const tmp = mkdtempSync(join(tmpdir(), "apx-blobs-"));
const rows = [];
for (const line of presets.split("\n")) {
  const m = line.match(
    /^\s+(\w+): \{ key: "(\w+)", label: "([^"]+)".*eyeColor: "(#[0-9A-Fa-f]+)", eyes: (\[.*\]) \},?$/,
  );
  if (!m) continue;
  const [, key, , label, eyeColor, eyes] = m;
  const out = join(tmp, `${key}.webp`);
  execFileSync("cwebp", [
    "-quiet",
    "-q",
    "82",
    "-alpha_q",
    "90",
    "-resize",
    "128",
    "128",
    join(web, "public/modules/blobs", `${key}.png`),
    "-o",
    out,
  ]);
  const uri = `data:image/webp;base64,${readFileSync(out).toString("base64")}`;
  rows.push(
    `  ${key}: { label: ${JSON.stringify(label)}, eyeColor: ${JSON.stringify(eyeColor)}, eyes: ${eyes}, src: ${JSON.stringify(uri)} },`,
  );
}
const body = `// AUTO-GENERATED by scripts/export-blobs.mjs from APX v1's blob export — do not edit by hand.
// Bodies are eyeless; eye rects live in the same 256x256 canvas and are drawn on top
// (animated) by <AgentAvatar>. An empty eye list = the face is baked into the body.

export type BlobEye = { x: number; y: number; w: number; h: number; rx: number };
export type BlobPreset = { label: string; eyeColor: string; eyes: BlobEye[]; src: string };

export const BLOB_VIEWBOX = 256;

export const BLOBS = {
${rows.join("\n")}
} satisfies Record<string, BlobPreset>;

/** Every blob key in the catalog: "menta", "noche", "kiwi", "coral"… */
export type BlobName = keyof typeof BLOBS;
export const BLOB_NAMES = Object.keys(BLOBS) as BlobName[];
`;
writeFileSync("src/blobs/catalog.ts", body);
console.log(`${rows.length} blobs → src/blobs/catalog.ts (${(body.length / 1024).toFixed(0)} KB)`);
