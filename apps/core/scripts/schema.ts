// Writes src/db/schema.ts (the table types the query builder checks against) from a freshly migrated database, so
// the types can never drift from the migrations. `--check` fails when the file is out of date.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { openDb } from "../src/db/db.ts";

const target = path.resolve(import.meta.dirname, "../src/db/schema.ts");
const home = fs.mkdtempSync(path.join(os.tmpdir(), "apx-schema-"));
const db = openDb(home, {});

type Column = { name: string; type: string; notnull: number; dflt_value: unknown; pk: number };
const pascal = (s: string) =>
  s
    .split("_")
    .map((p) => (p[0] ?? "").toUpperCase() + p.slice(1))
    .join("");

// Full-text index tables are read through `sql` fragments, not typed tables.
const tables = (
  db
    .prepare(
      "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '%_fts%' ORDER BY name",
    )
    .all() as Array<{ name: string }>
).map((t) => t.name);

const blocks = tables.map((t) => {
  const cols = db.prepare(`PRAGMA table_info(${t})`).all() as Column[];
  const fields = cols.map((c) => {
    const base = /INT/i.test(c.type) ? "number" : "string";
    const type = !c.notnull && !c.pk ? `${base} | null` : base;
    // A column with a default (or an integer primary key) may be left out of an insert.
    const generated = c.dflt_value !== null || (c.pk && /INT/i.test(c.type));
    return `  ${c.name}: ${generated ? `Generated<${type}>` : type};`;
  });
  return `export interface ${pascal(t)}Table {\n${fields.join("\n")}\n}`;
});

const out = `// Generated by \`node scripts/schema.ts\` from the migrations. Do not edit by hand.
import type { Generated } from "kysely";

${blocks.join("\n\n")}

export interface Database {
${tables.map((t) => `  ${t}: ${pascal(t)}Table;`).join("\n")}
}
`;
db.close();
fs.rmSync(home, { recursive: true, force: true });

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("src/db/schema.ts is out of date: run node scripts/schema.ts");
    process.exit(1);
  }
} else fs.writeFileSync(target, out);
